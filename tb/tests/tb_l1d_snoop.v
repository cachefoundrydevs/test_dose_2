`timescale 1ns/1ps
`include "l1d_defines.vh"
`include "tb_top_select.vh"
`define TEST_NAME "tb_l1d_snoop"
module tb_l1d_snoop;
`include "tb_dir_common.vh"
    reg  [WDW-1:0]    d;
    reg  [1:0]        st;
    reg               pr, dy, fnd, vd, vs;
    reg  [2:0]        vst;
    reg  [LINE*8-1:0] ld;
    integer           i0, n0, ar0, au0, t0, lat_snp, lat_snp_m, lat_snp_np, lat_upg, lat_stm, lat_ldm;
    task pulse_and_wait;
        input is_flush;
        integer t;
        begin
            @(negedge clk);
            if (is_flush) flush = 1'b1; else clean = 1'b1;
            @(negedge clk);
            flush = 1'b0;
            clean = 1'b0;
            t = 0;
            while (!(is_flush ? flush_complete : clean_complete) && t < 100000) begin
                @(posedge clk);
                t = t + 1;
            end
            check(t < 100000, "flush / clean never completed");
            @(negedge clk);
        end
    endtask
    initial begin
        repeat (5) @(posedge clk);
        @(negedge clk);
        rst = 1'b0;
        idle(5);
        sh_mode = 2'd1;
        req(C_LD, 0, 3, A(1,0,0), 0, d);
        peek_state(A(1,0,0), st);
        check(st == ST_E, "S1 plain load, not shared: E");
        snoop(A(1,0,0) + 5, 1'b0, pr, dy, ld);
        lat_snp = sa_t - snp_acc_t;
        check(pr && !dy, "S1 snoop read on E: present, clean");
        peek_state(A(1,0,0), st);
        check(st == ST_S, "S1 E -> S on snoop read");
        snoop(A(1,0,0), 1'b0, pr, dy, ld);
        peek_state(A(1,0,0), st);
        check(pr && !dy && st == ST_S, "S1 S stays S on snoop read");
        snoop(A(1,0,0), 1'b1, pr, dy, ld);
        peek_state(A(1,0,0), st);
        check(pr && !dy && st == ST_I, "S1 S -> I on snoop invalidate");
        snoop(A(1,0,0), 1'b1, pr, dy, ld);
        lat_snp_np = sa_t - snp_acc_t;
        check(!pr && !dy, "S1 snoop on an absent line: not present");
        sh_mode = 2'd2;
        req(C_LD, 0, 3, A(2,0,0), 0, d);
        peek_state(A(2,0,0), st);
        check(st == ST_S, "S2 plain load, shared: S");
        ar0 = n_ar; au0 = n_ar_uniq;
        send(C_ST, 0, 3, A(2,0,0), 64'h2222, i0); wait_resp(i0, d); lat_upg = got_t[i0] - snt_t[i0] - 1;
        peek_state(A(2,0,0), st);
        check(st == ST_M, "S2 store on S ends in M");
        check(n_ar == ar0 + 1 && n_ar_uniq == au0 + 1, "S2 store on S needs exactly one unique read");
        req(C_LD, 0, 3, A(2,0,0), 0, d);
        check(d == 64'h2222, "S2 data after the upgrade");
        sh_mode = 2'd1;
        au0 = n_ar_uniq;
        send(C_ST, 0, 3, A(3,0,0) + 8, 64'h3333_0000_3333, i0); wait_resp(i0, d); lat_stm = got_t[i0] - snt_t[i0] - 1;
        check(n_ar_uniq == au0 + 1, "S3 store miss is a unique read");
        peek_state(A(3,0,0), st);
        check(st == ST_M, "S3 store miss installs M");
        snoop(A(3,0,0), 1'b0, pr, dy, ld);
        lat_snp_m = sa_t - snp_acc_t;
        check(pr && dy, "S3 snoop read on M: present, dirty");
        check(ld[127:64] == 64'h3333_0000_3333, "S3 handed-over data holds the store");
        check(mem64(A(3,0,0) + 8) == 64'h3333_0000_3333, "S3 handed-over line written to memory");
        peek_state(A(3,0,0), st);
        check(st == ST_S, "S3 M -> S on snoop read");
        ar0 = n_ar;
        req(C_LD, 0, 3, A(3,0,0) + 8, 0, d);
        check(d == 64'h3333_0000_3333 && n_ar == ar0, "S3 load hits S with the stored data");
        req(C_ST, 0, 3, A(3,0,0) + 16, 64'h4444, d);
        snoop(A(3,0,0), 1'b1, pr, dy, ld);
        peek_state(A(3,0,0), st);
        check(pr && dy && st == ST_I, "S4 M -> I on snoop invalidate, data handed over");
        check(mem64(A(3,0,0) + 16) == 64'h4444, "S4 handed-over data in memory");
        ar0 = n_ar;
        send(C_LD, 0, 3, A(3,0,0) + 16, 0, i0); wait_resp(i0, d); lat_ldm = got_t[i0] - snt_t[i0] - 1;
        check(d == 64'h4444 && n_ar == ar0 + 1, "S4 next load fetches the handed-over data");
        req(C_LD, 0, 3, A(5,1,1), 0, d);
        peek_state(A(5,1,1), st);
        check(st == ST_E, "S5 E");
        ar0 = n_ar;
        req(C_ST, 0, 3, A(5,1,1), 64'h5555, d);
        peek_state(A(5,1,1), st);
        check(st == ST_M && n_ar == ar0, "S5 E -> M on a store hit, no memory read");
        sh_mode = 2'd2;
        req(C_LD, 0, 3, A(6,1,1), 0, d);
        peek_state(A(6,1,1), st);
        check(st == ST_S, "S6 S");
        au0 = n_ar_uniq;
        req(C_LR, 0, 3, A(6,1,1), 0, d);
        peek_state(A(6,1,1), st);
        check(st == ST_E && n_ar_uniq == au0 + 1, "S6 LR on S: upgrade to E with a unique read");
        check(d == pat64(A(6,1,1)), "S6 LR data");
        sh_mode = 2'd1;
        req(C_ST, 0, 3, A(7,2,2), 64'h7777, d);
        req(C_LD, 0, 3, A(8,2,2), 0, d);
        req(C_LD, 0, 3, A(9,2,2), 0, d);
        peek_state(A(7,2,2), st);
        peek_vc(A(7,2,2), fnd, vst, vd, vs);
        check(st == ST_I && fnd && vst == VC_VALID && vd, "S7 dirty line in a VALID victim slot");
        snoop(A(7,2,2), 1'b0, pr, dy, ld);
        check(pr && dy && ld[63:0] == 64'h7777, "S7 snoop read on the slot: present, dirty, data");
        check(mem64(A(7,2,2)) == 64'h7777, "S7 handed-over data in memory");
        peek_vc(A(7,2,2), fnd, vst, vd, vs);
        check(fnd && vst == VC_VALID && !vd && vs, "S7 slot now shared and clean");
        req(C_LD, 0, 3, A(7,2,2), 0, d);
        check(d == 64'h7777, "S7 load answered from the victim cache");
        idle(20);
        peek_state(A(7,2,2), st);
        check(st == ST_S, "S7 swap back installs S");
        req(C_LD, 0, 3, A(10,3,3), 0, d);
        req(C_LD, 0, 3, A(11,3,3), 0, d);
        req(C_LD, 0, 3, A(12,3,3), 0, d);
        peek_vc(A(10,3,3), fnd, vst, vd, vs);
        check(fnd && vst == VC_VALID && !vd, "S8 clean line in a VALID victim slot");
        snoop(A(10,3,3), 1'b1, pr, dy, ld);
        check(pr && !dy, "S8 snoop invalidate on the slot: present, clean");
        peek_vc(A(10,3,3), fnd, vst, vd, vs);
        check(!fnd, "S8 slot freed");
        ar0 = n_ar;
        req(C_LD, 0, 3, A(10,3,3), 0, d);
        check(n_ar == ar0 + 1 && d == pat64(A(10,3,3)), "S8 next load fetches again");
        hold_a = A(13,0,1);
        hold_v = 1'b1;
        send(C_LD, 0, 3, A(13,0,1), 0, i0);
        idle(20);
        snoop(A(13,0,1), 1'b1, pr, dy, ld);
        check(!pr && !dy, "S9 snoop during the fetch: not present");
        check(!got_v[i0], "S9 the load is still waiting for its data");
        hold_v = 1'b0;
        wait_resp(i0, d);
        check(d == pat64(A(13,0,1)), "S9 load data after the snoop");
        peek_state(A(13,0,1), st);
        check(st == ST_E, "S9 line installed after the snoop");
        sh_mode = 2'd2;
        req(C_LD, 0, 3, A(14,1,2), 0, d);
        sh_mode = 2'd1;
        req(C_ST, 0, 3, A(15,0,2), 64'hF00D, d);
        idle(10);
        pulse_and_wait(1'b0);
        peek_state(A(14,1,2), st);
        check(st == ST_S, "S10 clean keeps S as S");
        peek_state(A(15,0,2), st);
        check(st == ST_E, "S10 clean turns M into E");
        check(mem64(A(15,0,2)) == 64'hF00D, "S10 clean wrote the dirty line");
        pulse_and_wait(1'b1);
        peek_state(A(14,1,2), st);
        check(st == ST_I, "S10 flush: I");
        peek_state(A(15,0,2), st);
        check(st == ST_I, "S10 flush: I");
        check(!mem_err && !amo_err, "mem_err / amo_err must stay 0");
        $display("cycles: snoop answer after the snoop handshake: hit E %0d, hit M with data %0d, absent %0d",
                 lat_snp, lat_snp_m, lat_snp_np);
        $display("cycles: load miss %0d, store miss %0d, store on S (upgrade) %0d", lat_ldm, lat_stm, lat_upg);
        check(lat_upg == lat_stm, "a store on S must cost exactly a store miss");
        if (errors == 0) $display("TEST PASSED: tb_l1d_snoop");
        else             $display("TEST FAILED: tb_l1d_snoop (%0d errors)", errors);
        $finish;
    end
endmodule
